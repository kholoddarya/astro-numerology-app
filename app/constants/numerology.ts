// Расчёт числа имени
export function calculateNameNumber(fullName: string): number {
  const normalized = fullName.toLowerCase().replace(/[^а-яё]/g, "");

  if (!normalized) return 0;

  let sum = 0;
  for (const char of normalized) {
    const value = PYTHAGOREAN_TABLE[char];
    if (value !== undefined) {
      sum += value;
    }
  }

  // Сводим к однозначному числу или мастер-числу
  while (sum > 9 && ![11, 22, 33].includes(sum)) {
    sum = sum
      .toString()
      .split("")
      .reduce((acc, digit) => acc + parseInt(digit), 0);
  }

  return sum;
}

// Расчёт персонального года
export function calculatePersonalYear(
  birthDate: Date,
  currentYear: number,
): number {
  const day = birthDate.getDate();
  const month = birthDate.getMonth() + 1;

  // Сумма: день + месяц + текущий год
  let sum = day + month + currentYear;

  // Сводим к однозначному
  while (sum > 9 && ![11, 22, 33].includes(sum)) {
    sum = sum
      .toString()
      .split("")
      .reduce((acc, digit) => acc + parseInt(digit), 0);
  }

  return sum;
}

// Расчёт персонального месяца
export function calculatePersonalMonth(
  birthDate: Date,
  currentYear: number,
  currentMonth: number,
): number {
  const personalYear = calculatePersonalYear(birthDate, currentYear);
  let sum = personalYear + currentMonth;

  while (sum > 9 && ![11, 22, 33].includes(sum)) {
    sum = sum
      .toString()
      .split("")
      .reduce((acc, digit) => acc + parseInt(digit), 0);
  }

  return sum;
}

