// Функция генерации гороскопа на основе даты (детерминированная, но псевдослучайная)
export function generateDailyHoroscope(signId: string, date: Date): string {
  // Создаем "зерно" на основе даты, чтобы гороскоп был одинаковым в течение дня для всех
  const daySeed = date.getDate() + date.getMonth() + date.getFullYear();

  // Находим индекс знака для смещения (чтобы у всех знаков были разные комбинации)
  const signKeys = Object.keys(HOROSCOPE_TEMPLATES);
  const signIndex = signKeys.indexOf(signId);

  // Выбираем шаблон (всего 3 варианта на знак)
  const templateIndex = (daySeed + signIndex) % 3;
  const templates = HOROSCOPE_TEMPLATES[signId] || HOROSCOPE_TEMPLATES.aries;

  // Выбираем фразы
  const positiveIndex = (daySeed + signIndex * 2) % POSITIVE_PHRASES.length;
  const positive = POSITIVE_PHRASES[positiveIndex];

  const adviceList = ADVICE_PHRASES[signId] || ADVICE_PHRASES.aries;
  const adviceIndex = (daySeed + signIndex * 3) % adviceList.length;
  const advice = adviceList[adviceIndex];

  return templates[templateIndex]
    .replace("{{positive}}", positive)
    .replace("{{advice}}", advice);
}
